export function humanize(key) {
  if (/^\d+$/.test(key)) return `Item ${Number(key) + 1}`;
  const words = key
    .replace(/Html$/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/[_-]+/g, ' ')
    .trim()
    .toLowerCase();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

export const labelFor = (key) => labels[key] ?? humanize(String(key));
